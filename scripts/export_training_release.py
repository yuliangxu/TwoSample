#!/usr/bin/env python3
"""Export a completed, independently reproduced training run into this release.

Large fitted objects remain in the durable run directory. The release contains
training code, preserved inputs, exact synthetic outputs, provenance and figures.
"""
import argparse
import hashlib
import json
from pathlib import Path
import shutil

from prepare_run import validate_generation, verify_frozen_generation
from verify_from_training_release import verify_completed_report

ROOT = Path(__file__).resolve().parents[1]


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def copy_verified(source, target):
    target.parent.mkdir(parents=True, exist_ok=True)
    if target.exists():
        if sha(source) != sha(target):
            raise RuntimeError(f'Existing export differs; preserve it before replacing: {target}')
        return
    shutil.copy2(source, target)
    if sha(source) != sha(target):
        raise RuntimeError(f'Export copy did not verify: {target}')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('run_root', type=Path)
    args = parser.parse_args()
    run = args.run_root.resolve()
    analysis, generated = run / 'analysis', run / 'generators'
    for marker in (generated / 'COMPLETE', analysis / 'ANALYSIS_COMPLETE', analysis / 'COMPLETE'):
        if not marker.is_file():
            raise RuntimeError(f'Run incomplete: {marker}')
    inputs = json.loads((analysis / 'input_manifest.json').read_text())
    generation = verify_frozen_generation(analysis, inputs)
    validate_generation(generated / 'data/generation_manifest.json', inputs['inputs'], ROOT)
    for name, digest in inputs['source_scripts'].items():
        local = ROOT / Path(name).relative_to('source')
        if sha(local) != digest:
            raise RuntimeError(f'Release analysis source differs from executed source: {local}')
    checks = json.loads((analysis / 'analysis_validation.json').read_text())
    verify_completed_report(analysis)
    if (checks['validated_comparisons'] != 8 or checks['validated_estimator_fits'] != 24
            or checks['validated_figures'] != 7 or not checks['all_generators_trained_from_scratch']
            or checks['independent_training_reproductions_verified'] != 4):
        raise RuntimeError('Incomplete analysis validation')
    for name, expected in inputs['inputs'].items():
        source = analysis / 'inputs' / name
        if sha(source) != expected['sha256']:
            raise RuntimeError(f'Changed input: {name}')
        copy_verified(source, ROOT / 'data' / name)
    copy_verified(generated / 'data/generation_manifest.json', ROOT / 'data/generation_manifest.json')
    for name in generation['validation_artifacts']:
        copy_verified(generated / 'data' / name, ROOT / 'data' / name)
    final = ROOT / 'results/final'
    top = ['ANALYSIS_COMPLETE', 'COMPLETE', 'BATTS_commit.txt', 'REPORT.md', 'case_study_report.pdf',
           'input_manifest.json', 'input_checksums.csv', 'settings.R', 'settings.json', 'sessionInfo.txt',
           'interval_summary.csv', 'boosting_cv_summary.csv', 'analysis_validation.json',
           'report_manifest.json', 'timing.csv']
    for name in top:
        copy_verified(analysis / name, final / name)
    for pattern in ('figures/*.pdf', 'figures/*_plot_data.csv', 'figures/sessionInfo.txt',
                    'revision/*/*.csv', 'null/*.csv', 'null/*.txt'):
        for source in sorted(analysis.glob(pattern)):
            copy_verified(source, final / source.relative_to(analysis))
    summary = {'scope': 'All four generators trained from preserved observations; no pretrained model inputs.',
               'run_root': str(run), 'generation_manifest_sha256': sha(ROOT / 'data/generation_manifest.json'),
               'report_sha256': sha(final / 'case_study_report.pdf'),
               'model_order': generation['model_order'], 'independent_full_runs': 2,
               'training_source_files': len(generation['source_hashes']),
               'analysis': checks}
    target = ROOT / 'reproducibility/from_training_validation.json'
    target.write_text(json.dumps(summary, indent=2) + '\n')
    (final / 'README.md').write_text(
        '# Final analysis from reproducible training\n\n'
        'All four generators were fitted twice independently from the preserved training matrix. '
        'Each pair produced identical parameters and synthetic samples. '
        'The neural training budgets were completed in full.\n\n'
        'Training evidence and exact input/output hashes are in `../../data/generation_manifest.json` '
        'and `../../data/evidence/`. The PDF contains all seven figures; CSV exports accompany them. '
        'Large model objects and posterior draws are regenerated by the documented commands.\n')
    files = {}
    for path in sorted(ROOT.rglob('*')):
        rel = path.relative_to(ROOT)
        if (not path.is_file() or rel.parts[0] in {'.git', 'output'} or '__pycache__' in rel.parts
                or path.suffix == '.pyc' or rel.as_posix() == 'release_manifest.json'):
            continue
        files[rel.as_posix()] = sha(path)
    release = {'schema': 'twosample-from-training-release-v1', 'model_order': generation['model_order'],
               'BATTS_commit': inputs['BATTS_commit'], 'files': files,
               'generation_manifest_sha256': sha(ROOT / 'data/generation_manifest.json'),
               'pretrained_model_inputs': [], 'independent_full_training_runs': 2}
    (ROOT / 'release_manifest.json').write_text(json.dumps(release, indent=2) + '\n')
    print(f'Exported completed from-training release: {len(files)} files; {final}')


if __name__ == '__main__':
    main()
